#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	size_t	i;
	size_t	j;
	char	*res;
	size_t	t;

	i = 0;
	j = 0;
	if (!s1 || !s2)
		return (NULL);
	t = ft_strlen(s1) + ft_strlen(s2);
	res = (char *)malloc(sizeof(char) * (t + 1));
	if (!res)
		return (NULL);
	while (s1[i])
	{
		res[i] = s1[i];
		i++;
	}
	while (s2[j])
	{
		res[i + j] = s2[j];
		j++;
	}
	res[i + j] = '\0';
	return (res);
}
